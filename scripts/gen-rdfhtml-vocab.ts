// Derives the renderer's lookup tables (element class -> tag name, attribute
// property -> content attribute name, void elements) from the vendored RDF/HTML
// vocabulary, so the materializer stays driven by the ontology rather than by a
// hand-maintained table.
import { readFileSync, writeFileSync } from 'node:fs'
import { Parser, Store } from 'n3'

const SRC = 'ontology/vendor/rdf-html-2026-07-18.ttl'
const OUT = 'src/vocab/rdfhtml.generated.ts'
const H = 'https://ia2.dev/spec/rdf-html#'
const RDF_TYPE = 'http://www.w3.org/1999/02/22-rdf-syntax-ns#type'
const SUBCLASS = 'http://www.w3.org/2000/01/rdf-schema#subClassOf'

const store = new Store(new Parser().parse(readFileSync(SRC, 'utf8')))
const local = (iri: string) => iri.slice(H.length)

const tags: Record<string, string> = {}
for (const q of store.getQuads(null, H + 'tagName', null, null)) tags[local(q.subject.value)] = q.object.value

const voids = store
  .getQuads(null, SUBCLASS, H + 'VoidElement', null)
  .map((q) => local(q.subject.value))
  .filter((name) => name in tags)
  .sort()

const attrs: Record<string, string> = {}
for (const q of store.getQuads(null, RDF_TYPE, H + 'AttributeDefinition', null)) {
  const name = store.getQuads(q.subject, H + 'attributeLocalName', null, null)[0]
  if (name) attrs[local(q.subject.value)] = name.object.value
}

const sorted = (o: Record<string, string>) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)))

writeFileSync(
  OUT,
  `// Generated by scripts/gen-rdfhtml-vocab.ts from ${SRC}. Do not edit.
export const RDFHTML_SNAPSHOT = '2026-07-18'
/** Element class local name -> HTML tag name. */
export const TAG_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(sorted(tags), null, 2)}
/** Element classes that are void (no children). */
export const VOID_ELEMENTS: ReadonlySet<string> = new Set(${JSON.stringify(voids)})
/** Attribute property local name -> HTML content attribute name. */
export const ATTRIBUTE_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(sorted(attrs), null, 2)}
`,
)
console.log(`wrote ${OUT}: ${Object.keys(tags).length} elements, ${voids.length} void, ${Object.keys(attrs).length} attributes`)
